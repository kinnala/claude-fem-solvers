"""Adaptive P2 finite element solver for a variable-coefficient Poisson problem
in the unit cube.

Strong form
-----------
    -div(k grad u) = f        in  Omega = (0, 1)^3,
    k du/dn        = +1       on  front (z = 0),
    k du/dn        = -1       on  back  (z = 1),
    u              = 0        on  left, right, bottom, top (x = 0, 1 and y = 0, 1),

with k(x, y, z) = x y z + 1, f = 0 and n the outward unit normal.
The problem is nondimensional, stationary and linear.

Weak form
---------
Find u in V = {v in H^1(Omega) : v = 0 on Gamma_D} such that

    int_Omega k grad u . grad v dx = int_Omega f v dx + int_{Gamma_N} g v ds

for all v in V, where Gamma_N = front U back and g = k du/dn.

Adaptivity
----------
SOLVE -> ESTIMATE -> MARK -> REFINE with the residual estimator

    eta_T^2 = h_T^2 ||f + div(k grad u_h)||_T^2
            + 1/2 sum_{interior F in dT} h_F ||[[k grad u_h . n]]||_F^2
            +     sum_{F in dT on Gamma_N} h_F ||g - k grad u_h . n||_F^2,

Doerfler (bulk) marking with parameter theta, and refinement through
``MeshTet.refined(marked)`` (followed by re-tagging the cube faces). The loop stops before the number of P2 DOFs
would exceed ``max_dofs``. The initial mesh is generated by scikit-fem
(no Gmsh is needed for a cube).
"""
import argparse
import csv
import logging
from dataclasses import dataclass, field
from typing import Callable, Dict, List

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402
from skfem import (  # noqa: E402
    Basis,
    BilinearForm,
    ElementTetDG,
    ElementTetP1,
    ElementTetP2,
    FacetBasis,
    Functional,
    InteriorFacetBasis,
    LinearForm,
    MeshTet,
    condense,
    solve,
)
from skfem.helpers import dot, grad  # noqa: E402

# ---------------------------------------------------------------------------
# Parameters
# ---------------------------------------------------------------------------

PARAMS = {
    "n0": 3,             # initial mesh: nodes per direction of the cube
    "theta": 0.5,        # Doerfler bulk parameter
    "max_dofs": 10000,   # upper bound for P2 DOFs in the final system
    "outdir": ".",
}


@dataclass
class Problem:
    """Data of -div(k grad u) = f with homogeneous Dirichlet data on
    ``dirichlet`` and Neumann data g(x, n) = k du/dn on the ``neumann``
    boundaries. All callables act on coordinate arrays of shape (3, ...)."""

    k: Callable
    grad_k: Callable
    f: Callable
    neumann: Dict[str, Callable] = field(default_factory=dict)
    dirichlet: List[str] = field(default_factory=list)


def k_coef(x):
    return x[0] * x[1] * x[2] + 1.0


def grad_k_coef(x):
    return np.array([x[1] * x[2], x[0] * x[2], x[0] * x[1]])


PROBLEM = Problem(
    k=k_coef,
    grad_k=grad_k_coef,
    f=lambda x: 0.0 * x[0],
    neumann={
        "front": lambda x, n: 1.0 + 0.0 * x[0],
        "back": lambda x, n: -1.0 + 0.0 * x[0],
    },
    dirichlet=["left", "right", "bottom", "top"],
)

ELEMENT = ElementTetP2()


# ---------------------------------------------------------------------------
# Mesh
# ---------------------------------------------------------------------------

def build_mesh(n0=PARAMS["n0"]):
    """Unit cube with tetrahedra; boundary tags left/right (x=0/1),
    bottom/top (y=0/1), front/back (z=0/1)."""
    s = np.linspace(0.0, 1.0, n0)
    return MeshTet.init_tensor(s, s, s).with_defaults()


def p2_dofs(mesh):
    """Number of P2 DOFs (vertices + edges) of a tetrahedral mesh."""
    return mesh.nvertices + mesh.nedges


# ---------------------------------------------------------------------------
# Forms
# ---------------------------------------------------------------------------

def stiffness_form(problem):
    @BilinearForm
    def a(u, v, w):
        return problem.k(w.x) * dot(grad(u), grad(v))
    return a


def load_form(problem):
    @LinearForm
    def l(v, w):
        return problem.f(w.x) * v
    return l


def neumann_form(g):
    @LinearForm
    def l(v, w):
        return g(w.x, w.n) * v
    return l


def element_residual(problem):
    """|f + div(k grad u_h)|^2 with div(k grad u_h) = grad k . grad u_h
    + k lap u_h; ``w.lap`` holds the (exact) Laplacian of u_h."""
    @Functional
    def r(w):
        res = (problem.f(w.x) + dot(problem.grad_k(w.x), grad(w.uh))
               + problem.k(w.x) * w.lap)
        return res ** 2
    return r


def jump_residual(problem):
    @Functional
    def j(w):
        return (problem.k(w.x) * dot(grad(w.u1) - grad(w.u2), w.n)) ** 2
    return j


def neumann_residual(problem, g):
    @Functional
    def r(w):
        return (g(w.x, w.n) - problem.k(w.x) * dot(grad(w.uh), w.n)) ** 2
    return r


# ---------------------------------------------------------------------------
# Solve and estimate
# ---------------------------------------------------------------------------

def assemble_and_solve(mesh, problem=PROBLEM):
    basis = Basis(mesh, ELEMENT)
    A = stiffness_form(problem).assemble(basis)
    b = load_form(problem).assemble(basis)
    for name, g in problem.neumann.items():
        fb = FacetBasis(mesh, ELEMENT, facets=mesh.boundaries[name])
        b = b + neumann_form(g).assemble(fb)
    D = basis.get_dofs(problem.dirichlet)
    u = solve(*condense(A, b, D=D))
    return basis, u


def _diameters(p, idx):
    """Max distance between the vertices listed in columns of ``idx``."""
    nv = idx.shape[0]
    h = np.zeros(idx.shape[1])
    for i in range(nv):
        for j in range(i + 1, nv):
            h = np.maximum(h, np.linalg.norm(p[:, idx[i]] - p[:, idx[j]],
                                             axis=0))
    return h


def estimate(basis, u, problem=PROBLEM):
    """Return eta_T (per element) of the residual estimator."""
    mesh = basis.mesh
    hT = _diameters(mesh.p, mesh.t)
    hF = _diameters(mesh.p, mesh.facets)

    # Exact Laplacian of u_h: grad u_h is piecewise linear, so its L2
    # projection onto discontinuous P1 is exact and can be differentiated.
    dgbasis = basis.with_element(ElementTetDG(ElementTetP1()))
    uh = basis.interpolate(u)
    lap = sum(dgbasis.interpolate(dgbasis.project(uh.grad[i])).grad[i]
              for i in range(3))
    eta2 = hT ** 2 * element_residual(problem).elemental(basis, uh=uh,
                                                          lap=lap)

    # interior jumps, split half/half between the two neighbours
    fbs = [InteriorFacetBasis(mesh, ELEMENT, side=i) for i in [0, 1]]
    jmp = jump_residual(problem).elemental(
        fbs[0], u1=fbs[0].interpolate(u), u2=fbs[1].interpolate(u))
    tmp = np.zeros(mesh.nfacets)
    tmp[fbs[0].find] = hF[fbs[0].find] * jmp
    eta2 += 0.5 * np.sum(tmp[mesh.t2f], axis=0)

    # Neumann residuals, each boundary facet belongs to one element
    for name, g in problem.neumann.items():
        facets = mesh.boundaries[name]
        fb = FacetBasis(mesh, ELEMENT, facets=facets)
        vals = neumann_residual(problem, g).elemental(
            fb, uh=fb.interpolate(u))
        np.add.at(eta2, mesh.f2t[0, facets], hF[facets] * vals)

    return np.sqrt(eta2)


def doerfler_mark(eta, theta):
    """Smallest set of elements with sum eta_T^2 >= theta * sum eta^2."""
    e2 = eta ** 2
    order = np.argsort(-e2)
    cum = np.cumsum(e2[order])
    nmark = np.searchsorted(cum, theta * cum[-1]) + 1
    return order[:nmark]


def adaptive_loop(mesh, theta=PARAMS["theta"], max_dofs=PARAMS["max_dofs"],
                  problem=PROBLEM, verbose=True):
    """Run SOLVE-ESTIMATE-MARK-REFINE. Returns a list of dicts with keys
    mesh, basis, u, eta_T, eta, ndofs."""
    if p2_dofs(mesh) > max_dofs:
        raise ValueError("initial mesh already exceeds max_dofs")
    steps = []
    while True:
        basis, u = assemble_and_solve(mesh, problem)
        eta_T = estimate(basis, u, problem)
        eta = np.sqrt(np.sum(eta_T ** 2))
        steps.append({"mesh": mesh, "basis": basis, "u": u, "eta_T": eta_T,
                      "eta": eta, "ndofs": basis.N})
        if verbose:
            print(f"step {len(steps) - 1:3d}  elements {mesh.nelements:7d}  "
                  f"dofs {basis.N:6d}  eta {eta:.4e}")
        # adaptive MeshTet refinement does not carry the boundary tags over
        # correctly (facet indices change), so re-tag the cube faces
        refined = mesh.refined(doerfler_mark(eta_T, theta)).with_defaults()
        if p2_dofs(refined) > max_dofs:
            break
        mesh = refined
    return steps


# ---------------------------------------------------------------------------
# Postprocessing
# ---------------------------------------------------------------------------

def plot_boundary_mesh(mesh, ndofs, path, problem=PROBLEM):
    from mpl_toolkits.mplot3d.art3d import Poly3DCollection

    neumann = set(problem.neumann)
    fig = plt.figure(figsize=(11, 5.5))
    for k, (elev, azim) in enumerate([(-30, -60), (30, -60)]):
        ax = fig.add_subplot(1, 2, k + 1, projection="3d")
        for name, facets in mesh.boundaries.items():
            tris = mesh.p[:, mesh.facets[:, facets]].transpose(2, 1, 0)
            color = "tab:orange" if name in neumann else "lightgray"
            ax.add_collection3d(Poly3DCollection(
                tris, facecolors=color, edgecolors="k", linewidths=0.2))
        ax.set_xlim(0, 1)
        ax.set_ylim(0, 1)
        ax.set_zlim(0, 1)
        ax.set_box_aspect((1, 1, 1))
        ax.view_init(elev=elev, azim=azim)
        ax.set_xlabel("x")
        ax.set_ylabel("y")
        ax.set_zlabel("z")
    fig.suptitle(f"final mesh: {mesh.nelements} elements, {ndofs} DOFs "
                 "(orange: Neumann front/back, gray: Dirichlet)\n"
                 "left: front z=0 seen from below; "
                 "right: back z=1 seen from above")
    fig.tight_layout()
    fig.savefig(path, dpi=150)
    plt.close(fig)


def postprocess(steps, outdir="."):
    import os
    os.makedirs(outdir, exist_ok=True)

    ndofs = np.array([s["ndofs"] for s in steps])
    etas = np.array([s["eta"] for s in steps])

    with open(os.path.join(outdir, "convergence.csv"), "w", newline="") as fh:
        wr = csv.writer(fh)
        wr.writerow(["step", "elements", "dofs", "eta"])
        for i, s in enumerate(steps):
            wr.writerow([i, s["mesh"].nelements, s["ndofs"], s["eta"]])

    # estimator vs DOFs with N^{-2/3} reference slope (optimal for P2 in 3D)
    fig, ax = plt.subplots(figsize=(6, 4.5))
    ax.loglog(ndofs, etas, "o-", label=r"adaptive, $\eta$")
    ref = etas[0] * (ndofs / ndofs[0]) ** (-2.0 / 3.0)
    ax.loglog(ndofs, ref, "k--", label=r"$\mathcal{O}(N^{-2/3})$")
    ax.set_xlabel("number of DOFs $N$")
    ax.set_ylabel(r"error estimator $\eta$")
    ax.grid(True, which="both", alpha=0.3)
    ax.legend()
    fig.tight_layout()
    fig.savefig(os.path.join(outdir, "estimator_vs_dofs.png"), dpi=150)
    plt.close(fig)

    # final adapted mesh: boundary surface, Neumann faces highlighted,
    # seen from the front (z=0) side and from the back (z=1) side
    plot_boundary_mesh(steps[-1]["mesh"], steps[-1]["ndofs"],
                       os.path.join(outdir, "final_mesh.png"))

    # VTK export: initial, midway and final step
    last = len(steps) - 1
    for label, i in [("initial", 0), ("midway", last // 2), ("final", last)]:
        s = steps[i]
        s["mesh"].save(
            os.path.join(outdir, f"solution_{label}.vtk"),
            point_data={"u": s["u"][s["basis"].nodal_dofs[0]]},
            cell_data={"eta": [s["eta_T"]]},
        )

    if len(steps) > 1:
        rate = -np.polyfit(np.log(ndofs[-4:]), np.log(etas[-4:]), 1)[0]
        print(f"observed rate (last steps): eta ~ N^(-{rate:.2f})")
    print(f"final: {steps[-1]['ndofs']} DOFs, eta = {etas[-1]:.4e}")


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--n0", type=int, default=PARAMS["n0"],
                    help="initial mesh nodes per direction (default 3)")
    ap.add_argument("--theta", type=float, default=PARAMS["theta"],
                    help="Doerfler bulk parameter (default 0.5)")
    ap.add_argument("--max-dofs", type=int, default=PARAMS["max_dofs"],
                    help="maximum number of P2 DOFs (default 10000)")
    ap.add_argument("--outdir", default=PARAMS["outdir"],
                    help="output directory (default .)")
    args = ap.parse_args(argv)
    logging.getLogger("skfem").setLevel(logging.ERROR)

    steps = adaptive_loop(build_mesh(args.n0), args.theta, args.max_dofs)
    postprocess(steps, args.outdir)
    return steps


if __name__ == "__main__":
    main()
